function pad(value: number) {
  return String(value).padStart(2, '0')
}

function plural(value: number, forms: [string, string, string]) {
  const abs = Math.abs(value) % 100
  const last = abs % 10
  if (abs > 10 && abs < 20) return forms[2]
  if (last > 1 && last < 5) return forms[1]
  if (last === 1) return forms[0]
  return forms[2]
}

function formatNumber(value: number) {
  return value.toLocaleString('ru-RU')
}

function getTargetDate(now: Date, nextMode: Mode) {
  const targetDay = nextMode === 'calendar' ? 1 : 21
  const year = now.getFullYear()
  const target = new Date(year, 5, targetDay, 0, 0, 0, 0)
  if (now.getTime() >= target.getTime()) {
    return new Date(year + 1, 5, targetDay, 0, 0, 0, 0)
  }
  return target
}

function updateCountdown() {
  const now = new Date()
  const target = getTargetDate(now, mode.value)
  targetDate.value = target
  const diff = Math.max(0, target.getTime() - now.getTime())
  const days = Math.floor(diff / 86400000)
  const hours = Math.floor((diff % 86400000) / 3600000)
  const minutes = Math.floor((diff % 3600000) / 60000)
  const seconds = Math.floor((diff % 60000) / 1000)
  timeLeft.value = { days, hours, minutes, seconds }
}

